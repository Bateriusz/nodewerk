#!/usr/bin/env python3
"""Regenerate or inspect planning catalogs; never changes engine/runtime inputs."""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import re

import werkkzeug3_catalog
import werkkzeug4_catalog


ROOT = Path(__file__).resolve().parents[1]
CATALOG_DIR = ROOT / "references" / "operator_catalog"
EXTRACTORS = {
    "werkkzeug3.json": werkkzeug3_catalog,
    "werkkzeug4.json": werkkzeug4_catalog,
}


def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def unique(values: list[str], label: str) -> None:
    require(len(values) == len(set(values)), f"Duplicate {label}")


def validate(catalogs: dict[str, dict], capabilities: dict, technologies: dict) -> None:
    all_keys = []
    for filename, catalog in catalogs.items():
        require(catalog["schema_version"] == 1, f"Unsupported schema in {filename}")
        revision = catalog["source_revision"]
        require(revision == EXTRACTORS[filename].SOURCE_REVISION,
                f"Unexpected reference revision in {filename}")
        require(catalog["source_repository"] == "https://github.com/farbrausch/fr_public",
                f"Unexpected source repository in {filename}")
        sources = {source["path"]: source for source in catalog["source_files"]}
        require(len(sources) == len(catalog["source_files"]), f"Duplicate source in {filename}")
        for source in sources.values():
            require(bool(re.fullmatch(r"[a-f0-9]{40}", source["git_blob_sha"])),
                    f"Invalid blob SHA: {source['path']}")
        for operator in catalog["operators"]:
            all_keys.append(operator["key"])
            source = operator["source"]
            require(source["path"] in sources, f"Unknown source: {operator['key']}")
            expected = f"https://github.com/farbrausch/fr_public/blob/{revision}/{source['path']}"
            require(source["url"].startswith(expected + "#L"),
                    f"Unpinned source URL: {operator['key']}")
    unique(all_keys, "reference keys")

    families = capabilities["families"]
    unique([family["id"] for family in families], "capability families")
    source_ids = [source["id"] for source in capabilities["sources"]]
    unique(source_ids, "capability sources")
    priorities = {item["priority"] for item in capabilities["priority_order"]}
    for family in families:
        require(family["priority"] in priorities, f"Unknown priority: {family['id']}")
        for source_id in family["source_refs"]:
            require(source_id in source_ids, f"Unknown capability source: {source_id}")
        for dimension, status in family["coverage"].items():
            require(status in capabilities["coverage_definitions"][dimension],
                    f"Unknown {dimension}: {family['id']}")
        require(family["current_state"] in capabilities["coverage_definitions"]["current_state"],
                f"Unknown implementation state: {family['id']}")
    unique([candidate["id"] for candidate in technologies["candidates"]], "technology candidates")
    for candidate in technologies["candidates"]:
        require(candidate["eligibility"] in {"allowed", "conditional", "excluded"},
                f"Unknown eligibility: {candidate['id']}")
        for source_id in candidate["sources"]:
            require(source_id in technologies["sources"], f"Unknown technology source: {source_id}")


def cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def render_overview(catalogs: dict[str, dict], capabilities: dict, technologies: dict) -> str:
    w3 = catalogs["werkkzeug3.json"]
    w4 = catalogs["werkkzeug4.json"]
    counts = Counter((operator["variant"], operator["registry"]) for operator in w3["operators"])
    lines = [
        "# Operator catalog overview", "",
        "Generated by `python tools/operator_catalog.py generate`. See [README.md](README.md)",
        "for scope, limitations and regeneration instructions. These are planning data,",
        "not a claim that NW-13 or complete demo reproduction is implemented.", "",
        f"Reference revision: `{w3['source_revision']}`.", "",
        f"Reviewed nodewerk revision: `{capabilities['reviewed_nodewerk_revision']}`.", "",
        "## Extracted declarations", "",
        "| Reference | Registry / scope | Records |", "| --- | --- | ---: |",
    ]
    for (variant, registry), count in sorted(counts.items()):
        lines.append(f"| `{variant}` | `{registry}` | {count} |")
    lines.extend([
        f"| Werkkzeug4 | All {len(w4['source_files'])} `.ops` files under `altona_wz4` | {len(w4['operators'])} |",
        "", "Records in different variants may describe the same function. Wz4 includes",
        "hidden, obsolete, conversion, test and proof-of-concept declarations, with",
        "overlapping tags. Enabled-build availability and production usage are separate",
        "questions. Parameter extraction is static and has documented limitations.", "",
        f"Verified source files: {len(w3['source_files'])} for Wz3 and {len(w4['source_files'])} for Wz4.",
        "", "## Current nodewerk capabilities", "",
        "The state describes only the reviewed scope in [capability_map.json](capability_map.json).",
        "`partial` is functional scope, not a measured fraction of historical operators.",
        "Reference equivalence remains `unreviewed` until concrete operators/subgraphs are mapped.", "",
        "| Capability family | Implementation state | Current scope coverage | Priority |",
        "| --- | --- | --- | ---: |",
    ])
    for family in capabilities["families"]:
        lines.append(f"| {cell(family['title'])} | `{family['current_state']}` | `{family['coverage']['current_capability']}` | {family['priority']} |")
    lines.extend(["", "## Implementation candidates", "",
                  "Eligibility follows the no-owned-training policy. It does not mean an SDK",
                  "is integrated, adopted, required or available on every target profile.", "",
                  "| Candidate | Eligibility | Training | Current integration |",
                  "| --- | --- | --- | --- |"])
    for candidate in technologies["candidates"]:
        lines.append(f"| `{candidate['id']}` | `{candidate['eligibility']}` | `{candidate['training']}` | `{candidate['current_integration']}` |")
    lines.extend(["", "## Open analysis", "",
                  "- Extract reachable operator use from selected demo graphs/pages.",
                  "- Review exact reference parameters, domains and downstream consumers.",
                  "- Add explicit many-to-many replacement decisions with evidence.",
                  "- Implement selected capabilities through the shared graph/Studio/compiler/player path.",
                  "", "See [the roadmap](../../docs/operator-roadmap.md) and",
                  "[NW-13](https://github.com/Bateriusz/nodewerk/issues/36) for implementation scope.", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("generate", "check", "summary"))
    parser.add_argument("--reference-root", type=Path,
                        default=ROOT / "references" / "farbrausch" / "fr_public")
    parser.add_argument("--output-dir", type=Path, default=CATALOG_DIR,
                        help="Destination for generated inventories/overview; curated maps are read from the repository")
    args = parser.parse_args()
    capabilities = read_json(CATALOG_DIR / "capability_map.json")
    technologies = read_json(CATALOG_DIR / "technology_candidates.json")
    if args.command == "summary":
        catalogs = {name: read_json(args.output_dir / name) for name in EXTRACTORS}
    else:
        catalogs = {name: module.build_catalog(args.reference_root) for name, module in EXTRACTORS.items()}
    validate(catalogs, capabilities, technologies)
    outputs = {name: EXTRACTORS[name].serialize_catalog(catalog) for name, catalog in catalogs.items()}
    outputs["overview.md"] = render_overview(catalogs, capabilities, technologies)
    if args.command == "generate":
        args.output_dir.mkdir(parents=True, exist_ok=True)
        for name, content in outputs.items():
            (args.output_dir / name).write_text(content, encoding="utf-8", newline="\n")
    elif args.command == "check":
        for name, content in outputs.items():
            path = args.output_dir / name
            require(path.exists() and path.read_bytes() == content.encode("utf-8"),
                    f"Generated catalog is stale or missing: {path}. Run generate.")
    print(json.dumps({
        "status": "ok", "command": args.command,
        "reference_revision": catalogs["werkkzeug3.json"]["source_revision"],
        "werkkzeug3_registrations_including_variants": len(catalogs["werkkzeug3.json"]["operators"]),
        "werkkzeug4_declarations": len(catalogs["werkkzeug4.json"]["operators"]),
        "capability_families": len(capabilities["families"]),
        "technology_candidates": len(technologies["candidates"]),
        "demo_reachability": "pending_graph_extraction",
    }, indent=2))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError) as error:
        raise SystemExit(f"operator catalog: {error}") from error
