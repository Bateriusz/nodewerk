int RunSceneRenderer(const RendererOptions& options) {
    try {
        if (options.self_check) {
            std::fputs(
                "{\"format\":\"nw11-scene-renderer\",\"version\":1,"
                "\"status\":\"self_check_ok\"}\n",
                stdout);
            return kExitOk;
        }
        SceneRenderer renderer(options);
        return renderer.Run();
    } catch (const std::exception& error) {
        std::fprintf(
            stderr, "[NW11-RENDER-ERR][exit_code=%d] %s\n",
            kExitInitializationFailed, error.what());
        return kExitInitializationFailed;
    }
}

