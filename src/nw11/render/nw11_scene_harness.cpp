void ThrowIfFailed(HRESULT result, const char* stage) {
    if (FAILED(result)) {
        char buffer[256];
        std::snprintf(
            buffer, sizeof(buffer), "%s failed (HRESULT 0x%08lx)", stage,
            static_cast<unsigned long>(result));
        throw std::runtime_error(buffer);
    }
}

std::uint64_t Align(std::uint64_t value, std::uint64_t alignment) {
    return (value + alignment - 1u) & ~(alignment - 1u);
}

bool ParseAdapterLuid(const std::string& text, LUID& luid) {
    if (text.empty()) {
        return false;
    }
    unsigned long long high = 0;
    unsigned long long low = 0;
    if (std::sscanf(text.c_str(), "%llx:%llx", &high, &low) != 2 &&
        std::sscanf(text.c_str(), "%llu:%llu", &high, &low) != 2) {
        return false;
    }
    luid.HighPart = static_cast<LONG>(high);
    luid.LowPart = static_cast<DWORD>(low);
    return true;
}

std::string LuidString(const LUID& luid) {
    char buffer[32] = {};
    std::snprintf(
        buffer,
        sizeof(buffer),
        "%08lX:%08lX",
        static_cast<unsigned long>(luid.HighPart),
        static_cast<unsigned long>(luid.LowPart));
    return buffer;
}

std::string WideToUtf8(const wchar_t* text) {
    if (text == nullptr || text[0] == L'\0') {
        return {};
    }
    const int bytes =
        WideCharToMultiByte(CP_UTF8, 0, text, -1, nullptr, 0, nullptr, nullptr);
    if (bytes <= 1) {
        return {};
    }
    std::string output(static_cast<std::size_t>(bytes), '\0');
    WideCharToMultiByte(
        CP_UTF8, 0, text, -1, output.data(), bytes, nullptr, nullptr);
    output.resize(static_cast<std::size_t>(bytes - 1));
    return output;
}

std::uint32_t FloatBits(float value) {
    std::uint32_t bits = 0;
    std::memcpy(&bits, &value, sizeof(bits));
    return bits;
}

std::string JsonEscape(const std::string& value) {
    std::string out;
    out.reserve(value.size() + 8);
    for (char character : value) {
        switch (character) {
            case '\\': out += "\\\\"; break;
            case '"': out += "\\\""; break;
            case '\n': out += "\\n"; break;
            case '\r': out += "\\r"; break;
            case '\t': out += "\\t"; break;
            default:
                if (static_cast<unsigned char>(character) < 0x20) {
                    char buffer[8] = {};
                    std::snprintf(
                        buffer, sizeof(buffer), "\\u%04x",
                        static_cast<unsigned>(static_cast<unsigned char>(character)));
                    out += buffer;
                } else {
                    out.push_back(character);
                }
        }
    }
    return out;
}

std::string ReadFile(const std::string& path) {
    std::ifstream stream(path, std::ios::binary);
    if (!stream) {
        throw std::runtime_error("cannot open file: " + path);
    }
    std::ostringstream buffer;
    buffer << stream.rdbuf();
    return buffer.str();
}

std::vector<std::uint8_t> ReadBytes(const std::string& path) {
    std::ifstream stream(path, std::ios::binary);
    if (!stream) {
        throw std::runtime_error("cannot open file: " + path);
    }
    return std::vector<std::uint8_t>(
        std::istreambuf_iterator<char>(stream), std::istreambuf_iterator<char>());
}

