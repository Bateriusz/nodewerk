void WaitForFence(ID3D12CommandQueue* queue, ID3D12Fence* fence, HANDLE event,
                  std::uint64_t& value) {
    const std::uint64_t target = ++value;
    ThrowIfFailed(queue->Signal(fence, target), "ID3D12CommandQueue::Signal");
    if (fence->GetCompletedValue() < target) {
        ThrowIfFailed(
            fence->SetEventOnCompletion(target, event),
            "ID3D12Fence::SetEventOnCompletion");
        WaitForSingleObject(event, INFINITE);
    }
}

